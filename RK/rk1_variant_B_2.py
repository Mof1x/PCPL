"""
Рубежный контроль №1 по курсу «ПиК ЯП»
Вариант запросов: В
Вариант предметной области: 2 («Школьник — Класс»)
"""

from operator import itemgetter


class Pupil:
    """Школьник (сторона отношения «многие», аналог «Сотрудник»)."""

    def __init__(self, id, fio, score, class_id):
        self.id = id
        self.fio = fio
        self.score = score  # Количественный признак (например, учебный балл / рейтинг)
        self.class_id = class_id


class SchoolClass:
    """Класс (сторона отношения «один», аналог «Отдел»)."""

    def __init__(self, id, name):
        self.id = id
        self.name = name


class PupilClass:
    """
    Класс для реализации связи многие-ко-многим
    (Школьники и посещаемые ими классы/спецкурсы).
    """

    def __init__(self, class_id, pupil_id):
        self.class_id = class_id
        self.pupil_id = pupil_id


# Школьные классы
classes = [
    SchoolClass(1, "10-А математический"),
    SchoolClass(2, "11-Б гуманитарный"),
    SchoolClass(3, "9-В естественно-научный"),
    SchoolClass(4, "8-А инженерный"),
    SchoolClass(5, "11-А физико-математический"),
]

# Школьники
pupils = [
    Pupil(1, "Артамонов", 88, 1),
    Pupil(2, "Андреев", 94, 1),
    Pupil(3, "Петров", 76, 2),
    Pupil(4, "Аксёнов", 82, 2),
    Pupil(5, "Иванов", 69, 3),
    Pupil(6, "Смирнова", 91, 3),
    Pupil(7, "Алексеева", 85, 4),
    Pupil(8, "Васильев", 74, 5),
]

# Связь многие-ко-многим (школьники и профильные классы/элективы)
pupils_classes = [
    PupilClass(1, 1),
    PupilClass(1, 2),
    PupilClass(2, 3),
    PupilClass(2, 4),
    PupilClass(3, 1),  # Артамонов также посещает спецкурс 9-В
    PupilClass(3, 5),
    PupilClass(4, 7),
    PupilClass(5, 8),
    PupilClass(5, 2),  # Андреев также посещает спецкурс 11-А
]


def main():
    """Основная функция программы."""

    # 1. Соединение данных один-ко-многим
    one_to_many = [
        (p.fio, p.score, c.name)
        for c in classes
        for p in pupils
        if p.class_id == c.id
    ]

    # 2. Соединение данных многие-ко-многим
    many_to_many_temp = [
        (c.name, pc.class_id, pc.pupil_id)
        for c in classes
        for pc in pupils_classes
        if c.id == pc.class_id
    ]

    many_to_many = [
        (p.fio, p.score, class_name)
        for class_name, class_id, pupil_id in many_to_many_temp
        for p in pupils
        if p.id == pupil_id
    ]

    print("=" * 70)
    print("Рубежный контроль № 1 по курсу «ПиК ЯП»")
    print("Вариант запросов: В | Вариант предметной области: 2 («Школьник — Класс»)")
    print("=" * 70)

    # -------------------------------------------------------------------------
    # Запрос В1 (один-ко-многим):
    # Выведите список всех школьников, у которых фамилия начинается с буквы «А»,
    # и названия их классов.
    # -------------------------------------------------------------------------
    print("\nЗадание В1")
    print("Список школьников с фамилией на букву «А» и их классы (1:M):")
    res_1 = [
        (p_fio, c_name)
        for p_fio, _, c_name in one_to_many
        if p_fio.startswith("А")
    ]
    print(res_1)

    # -------------------------------------------------------------------------
    # Запрос В2 (один-ко-многим):
    # Выведите список классов с минимальным баллом школьников в каждом классе,
    # отсортированный по минимальному баллу.
    # -------------------------------------------------------------------------
    print("\nЗадание В2")
    print("Классы с минимальным баллом учащихся, отсортированные по возрастанию балла (1:M):")
    res_2_unsorted = []
    for c in classes:
        # Список школьников данного класса
        c_pupils = list(filter(lambda x: x[2] == c.name, one_to_many))
        if len(c_pupils) > 0:
            # Извлекаем баллы школьников класса
            c_scores = [score for _, score, _ in c_pupils]
            min_score = min(c_scores)
            res_2_unsorted.append((c.name, min_score))

    # Сортировка по минимальному баллу (по возрастанию)
    res_2 = sorted(res_2_unsorted, key=itemgetter(1))
    print(res_2)

    # -------------------------------------------------------------------------
    # Запрос В3 (многие-ко-многим):
    # Выведите список всех связанных школьников и классов,
    # отсортированный по школьникам (по алфавиту ФИО).
    # -------------------------------------------------------------------------
    print("\nЗадание В3")
    print("Список связанных школьников и классов, отсортированный по школьникам (M:M):")
    # Сортировка по первому элементу кортежа (ФИО школьника)
    res_3 = sorted(many_to_many, key=itemgetter(0))
    print(res_3)


if __name__ == "__main__":
    main()
